# --------------------------------------------------------------------------- #
# A blocked answer is not saved                                                #
# --------------------------------------------------------------------------- #
BLOCKING = {
    "output_guardrail": {"enable_output_guardrail": True, "output_guardrail_type": 1}
}
ANSWER = "risposta " * 50


def _turn(monkeypatch, verdict, *, buffered):
    async def fake_run_orchestrator(**_):
        return (
            OrchestratorOutput(status="ok", message=ANSWER, used_document_ids=[]),
            [],
            MagicMock(all_messages=lambda: []),
        )

    class FakeStream:
        async def deltas(self):
            yield ANSWER

        async def finalize(self):
            return await fake_run_orchestrator()

    @asynccontextmanager
    async def fake_stream_orchestrator(**_):
        yield FakeStream()

    async def fake_output_guardrail(**_):
        return verdict

    monkeypatch.setattr(orchestrator, "run_orchestrator", fake_run_orchestrator)
    monkeypatch.setattr(orchestrator, "stream_orchestrator", fake_stream_orchestrator)
    monkeypatch.setattr(guardrails, "output_guardrail", fake_output_guardrail)
    store = MagicMock()

    async def collect():
        return [
            json.loads(event)
            async for event in entrypoint.run_turn(
                rag_type="CHAT_RAG",
                search_text="domanda",
                deps=_deps(enable_verifier=buffered),
                store=store,
                chat_id="c1",
                user_id="u1",
                guardrails_configuration=BLOCKING,
            )
        ]

    return asyncio.run(collect()), store


@pytest.mark.parametrize("buffered", [False, True])
def test_cancelled_answer_is_not_saved(monkeypatch, buffered):
    events, store = _turn(monkeypatch, "HATE", buffered=buffered)

    assert events[-1] == {"chunk": streaming.OUTPUT_GUARDRAIL_CANCEL_MESSAGE, "type": "CANCEL"}
    store.save_turn.assert_not_called()


@pytest.mark.parametrize("buffered", [False, True])
def test_delivered_answer_is_saved(monkeypatch, buffered):
    events, store = _turn(monkeypatch, guardrails.SAFE, buffered=buffered)

    assert events[-1]["type"] == "END"
    store.save_turn.assert_called_once()


@pytest.mark.parametrize(
    "cancel, outcome",
    [(streaming.OUTPUT_GUARDRAIL_CANCEL_MESSAGE, "BLOCKED_OUTPUT"), ("Altro tema.", "OFF_SCOPE")],
)
def test_a_cancelled_answer_ends_the_request_with_its_outcome(monkeypatch, cancel, outcome):
    async def fake_run_turn(**_):
        yield json.dumps({"chunk": "", "type": "START"})
        yield json.dumps({"chunk": cancel, "type": "CANCEL"})

    monkeypatch.setattr(entrypoint, "run_turn", fake_run_turn)
    monkeypatch.setattr(entrypoint, "build_model", lambda _: MagicMock())
    records = []
    monkeypatch.setattr(entrypoint.logger, "info", records.append)

    async def collect():
        return [
            event
            async for event in entrypoint.get_agentic_rag(
                rag_type="CHAT_RAG",
                search_query=None,
                datasource_ids=None,
                after_key=None,
                suggest_keyword=None,
                suggestion_category_id=None,
                jwt=None,
                extra=None,
                sort=None,
                sort_after_key=None,
                language=None,
                search_text="domanda",
                chat_id=None,
                user_id=None,
                tenant_id="t1",
                retrieve_from_uploaded_documents=False,
                chat_history=None,
                timestamp=None,
                chat_sequence_number=1,
                rag_configuration={},
                llm_configuration={},
                guardrails_configuration={},
                opensearch_host="http://os",
                grpc_host_embedding="em:9000",
                grpc_host_datasource="ds:9000",
            )
        ]

    asyncio.run(collect())

    assert any(f"[request] end outcome={outcome}" in record for record in records)
