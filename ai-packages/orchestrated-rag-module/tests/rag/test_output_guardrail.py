def test_each_output_provider_gets_its_own_configuration(monkeypatch):
    seen = {}

    async def fake_bedrock(config, instruction, text):
        seen["bedrock"] = (config, instruction)
        return "NONE"

    def fake_armor(config, text, *, response=False):
        seen["armor"] = (config, response)
        return "NONE"

    monkeypatch.setattr(guardrails, "check_bedrock", fake_bedrock)
    monkeypatch.setattr(guardrails, "check_model_armor", fake_armor)
    monkeypatch.setattr(
        guardrails,
        "check_openai_moderation",
        lambda config, text: seen.setdefault("openai", config),
    )
    output_guardrail = {
        "output_guardrail_aws_bedrock": {"model": "bedrock"},
        "output_guardrail_google_model_armor": {"template_id": "armor"},
        "output_guardrail_openai_moderation": {"api_key": "openai"},
    }

    for provider in ("aws_bedrock", "google_model_armor_response", "openai_moderation"):
        asyncio.run(
            guardrails.classify_output(
                output_guardrail={**output_guardrail, "output_guardrail_provider": provider},
                categories=None,
                model=None,
                answer="risposta",
            )
        )

    assert seen["bedrock"][0] == {"model": "bedrock"}
    assert "output generated by the AI" in seen["bedrock"][1]
    assert seen["armor"] == ({"template_id": "armor"}, True)
    assert seen["openai"] == {"api_key": "openai"}


def test_model_armor_sanitizes_the_model_response(monkeypatch):
    module = types.ModuleType("google.cloud.modelarmor_v1")
    module.FilterMatchState = types.SimpleNamespace(MATCH_FOUND="MATCH")
    module.DataItem = lambda **kwargs: kwargs
    module.SanitizeModelResponseRequest = lambda **kwargs: kwargs
    client = MagicMock()
    client.sanitize_model_response.return_value = types.SimpleNamespace(
        sanitization_result=types.SimpleNamespace(filter_match_state="MATCH")
    )
    module.ModelArmorClient = MagicMock(return_value=client)
    cloud = types.ModuleType("google.cloud")
    cloud.modelarmor_v1 = module
    monkeypatch.setitem(sys.modules, "google.cloud", cloud)
    monkeypatch.setitem(sys.modules, "google.cloud.modelarmor_v1", module)

    config = {"region": "eu", "project_id": "p", "template_id": "t"}
    assert guardrails.check_model_armor(config, "testo", response=True) == guardrails.UNSAFE
    request = client.sanitize_model_response.call_args.kwargs["request"]
    assert request["model_response_data"] == {"text": "testo"}
    client.sanitize_user_prompt.assert_not_called()


