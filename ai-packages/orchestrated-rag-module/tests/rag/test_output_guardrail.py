def _scope_gate(answer_of_the_model):
    prompts = []

    def model(messages, info: AgentInfo) -> ModelResponse:
        prompts.append(messages[-1].parts[-1].content)
        return ModelResponse(parts=[TextPart(answer_of_the_model)])

    verdict = asyncio.run(
        guardrails.scope_gate(
            query="Chi e' il RUP?",
            context_text="Il RUP e' Mario Rossi.",
            answer_prefix="Il RUP {e'} Mario",
            output_guardrail={"scope_gate_domain_description": "appalti pubblici"},
            model=FunctionModel(model),
            deps=_deps(),
        )
    )
    return verdict, prompts[0]


def test_scope_gate_prompt_carries_domain_context_and_prefix():
    _, prompt = _scope_gate("VALID")

    assert "appalti pubblici" in prompt
    assert "Chi e' il RUP?" in prompt
    assert "Il RUP e' Mario Rossi." in prompt
    assert "Il RUP {e'} Mario" in prompt


