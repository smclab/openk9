def test_the_output_threshold_decides_not_the_input_one(guardrail_documents):
    guardrail_documents["scores"] = [0.75]
    configuration = {
        "input_guardrail": {"input_guardrail_threshold": 0.5},
        "output_guardrail": {"output_guardrail_threshold": 0.8},
    }

    assert _check(configuration) == guardrails.SAFE
    assert guardrail_documents["classified"] == []

    configuration["output_guardrail"]["output_guardrail_threshold"] = 0.7
    assert _check(configuration) == "HATE"


def test_the_answer_and_the_tenant_categories_are_classified(guardrail_documents):
    guardrail_documents["scores"] = [0.9]
    configuration = {
        "output_guardrail": {"output_guardrail_threshold": 0.8},
        "guardrail_categories": [{"name": "HATE", "description": "odio"}],
    }

    _check(configuration, answer="testo generato")

    call = guardrail_documents["classified"][0]
    assert call["answer"] == "testo generato"
    assert call["categories"] == "1. HATE - odio"


